function ContextMenuTrigger({
  onKeyDown,
  ...props
}: React.ComponentProps<typeof ContextMenuPrimitive.Trigger>) {
  const triggerRef = React.useRef<HTMLSpanElement>(null)

  // Radix only opens on `contextmenu`/long-press. Keyboard users open the menu
  // with Shift+F10 or the ContextMenu/Menu key; we forward that as a synthetic
  // contextmenu event so the primitive positions the menu at the trigger.
  const handleKeyDown = (event: React.KeyboardEvent<HTMLSpanElement>) => {
    onKeyDown?.(event)
    if (event.defaultPrevented) return
    if (event.key === "ContextMenu" || (event.shiftKey && event.key === "F10")) {
      event.preventDefault()
      const target = triggerRef.current ?? event.currentTarget
      const rect = target.getBoundingClientRect()
      target.dispatchEvent(
        new MouseEvent("contextmenu", {
          bubbles: true,
          cancelable: true,
          clientX: rect.left + rect.width / 2,
          clientY: rect.top + rect.height / 2,
        }),
      )
    }
  }

  return (
    <ContextMenuPrimitive.Trigger
      ref={triggerRef}
      data-slot="context-menu-trigger"
      onKeyDown={handleKeyDown}
      {...props}
    />
  )
}

