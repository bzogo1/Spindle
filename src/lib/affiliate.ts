/**
 * Affiliate program: accounts, tracking links, clicks, and conversions.
 *
 * DEVELOPMENT SEAM: state lives in process-local `Map`s, the same
 * interim-store pattern as `announcements.ts` / `newsletter-store.ts`. On
 * serverless or multi-instance deploys each instance keeps its own copy —
 * applications, clicks, and conversions are lost on restart and are not
 * shared between instances. The upgrade path is an `AffiliateAccount` /
 * `AffiliateClick` / `AffiliateConversion` table set; the exported function
 * signatures are already shaped for that swap.
 *
 * There are NO real payouts: `commissionCents` is a computed projection
 * (`amountCents * commissionRatePct / 100`) stored for reporting only.
 *
 * Server-only in practice: imported by route handlers and API tests; client
 * components must not import it.
 */

export type AffiliateStatus = "pending" | "active" | "suspended" | "rejected"

export const AFFILIATE_STATUSES: readonly AffiliateStatus[] = [
  "pending",
  "active",
  "suspended",
  "rejected",
]

export interface AffiliateAccount {
  id: string
  userId: string
  email: string
  status: AffiliateStatus
  /** Public tracking code embedded in share links (`AFF-XXXX-XXXX`). */
  code: string
  /** Whole-percent commission rate applied to conversion amounts. */
  commissionRatePct: number
  /** ISO timestamp — record creation time. */
  createdAt: string
}

export interface AffiliateClick {
  id: string
  code: string
  affiliateId: string
  /** ISO timestamp. */
  at: string
  /** Optional request metadata captured by the tracking endpoint. */
  userAgent?: string
  ip?: string
}

export interface AffiliateConversion {
  id: string
  code: string
  affiliateId: string
  /** ISO timestamp. */
  at: string
  amountCents?: number
  /** Computed at record time: `round(amountCents * rate / 100)`, absent when no amount. */
  commissionCents?: number
}

export interface AffiliateStats {
  clicks: number
  conversions: number
  revenueCents: number
  commissionCents: number
}

/** Hard caps so the in-memory store cannot grow without bound. */
export const AFFILIATES_STORE_MAX = 500
export const AFFILIATE_CLICKS_STORE_MAX = 50_000
export const AFFILIATE_CONVERSIONS_STORE_MAX = 10_000

/** Matches the `AFF-XXXX-XXXX` codes generated by `generateAffiliateCode`. */
export const AFFILIATE_CODE_PATTERN = /^AFF-[A-Z2-9]{4}-[A-Z2-9]{4}$/

export const DEFAULT_COMMISSION_RATE_PCT = 20

const CODE_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789" // no I/O/0/1

const affiliates = new Map<string, AffiliateAccount>() // id → account
const affiliatesByUser = new Map<string, string>() // userId → account id
const affiliatesByEmail = new Map<string, string>() // lowercase email → account id
const affiliatesByCode = new Map<string, string>() // code → account id
const clicks: AffiliateClick[] = []
const conversions: AffiliateConversion[] = []

function affiliateId(): string {
  return `aff_${crypto.randomUUID()}`
}

function clickId(): string {
  return `afc_${crypto.randomUUID()}`
}

function conversionId(): string {
  return `afv_${crypto.randomUUID()}`
}

function nowIso(): string {
  return new Date().toISOString()
}

/** Generates a unique `AFF-XXXX-XXXX` code not already in use. */
function generateAffiliateCode(): string {
  for (let attempt = 0; attempt < 50; attempt += 1) {
    const segment = () =>
      Array.from(
        { length: 4 },
        () => CODE_ALPHABET[crypto.getRandomValues(new Uint8Array(1))[0] % CODE_ALPHABET.length],
      ).join("")
    const code = `AFF-${segment()}-${segment()}`
    if (!affiliatesByCode.has(code)) return code
  }
  throw new Error("Could not allocate a unique affiliate code.")
}

function commissionCentsFor(account: AffiliateAccount, amountCents: number): number {
  return Math.round((amountCents * account.commissionRatePct) / 100)
}

export interface ApplyForAffiliateOptions {
  commissionRatePct?: number
}

/**
 * Submits an affiliate application for `userId`. Every user may hold at most
 * one account (any status — a rejected applicant must be re-activated by an
 * admin rather than re-applying), and each email may back at most one
 * account. New applications start `pending` with a unique tracking code.
 *
 * Throws `Error` with a user-facing message when the user already applied,
 * the email is already registered, or the capacity bound is reached — the
 * API route maps these to 409/400.
 */
export function applyForAffiliate(
  userId: string,
  email: string,
  options: ApplyForAffiliateOptions = {},
): AffiliateAccount {
  const normalizedUserId = userId.trim()
  const normalizedEmail = email.trim().toLowerCase()
  if (!normalizedUserId) throw new Error("A user id is required.")
  if (!normalizedEmail) throw new Error("An email address is required.")
  // Light format check: affiliate emails feed CSV exports, so reject values
  // that are clearly not addresses (no @, whitespace, or missing domain dot).
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(normalizedEmail)) {
    throw new Error("A valid email address is required.")
  }

  if (affiliatesByUser.has(normalizedUserId)) {
    throw new Error("You have already applied to the affiliate program.")
  }
  if (affiliatesByEmail.has(normalizedEmail)) {
    throw new Error("This email is already registered for the affiliate program.")
  }

  const rate = options.commissionRatePct ?? DEFAULT_COMMISSION_RATE_PCT
  if (!Number.isFinite(rate) || rate < 0 || rate > 100) {
    throw new Error("Commission rate must be a percentage between 0 and 100.")
  }

  // Bounded capacity: reject new applications once the store is full rather
  // than evicting live accounts.
  if (affiliates.size >= AFFILIATES_STORE_MAX) {
    throw new Error("The affiliate program is currently at capacity. Try again later.")
  }

  const account: AffiliateAccount = {
    id: affiliateId(),
    userId: normalizedUserId,
    email: normalizedEmail,
    status: "pending",
    code: generateAffiliateCode(),
    commissionRatePct: rate,
    createdAt: nowIso(),
  }

  affiliates.set(account.id, account)
  affiliatesByUser.set(normalizedUserId, account.id)
  affiliatesByEmail.set(normalizedEmail, account.id)
  affiliatesByCode.set(account.code, account.id)
  return account
}

/** The caller's affiliate account, or null when they never applied. */
export function getAffiliateByUserId(userId: string): AffiliateAccount | null {
  const id = affiliatesByUser.get(userId.trim())
  return id ? (affiliates.get(id) ?? null) : null
}

/** Looks up an account by its public tracking code (any status). */
export function getAffiliateByCode(code: string): AffiliateAccount | null {
  const id = affiliatesByCode.get(code.trim().toUpperCase())
  return id ? (affiliates.get(id) ?? null) : null
}

/**
 * Admin listing, newest application first. `status` filters to a single
 * status when provided.
 */
export function listAffiliates(status?: AffiliateStatus): AffiliateAccount[] {
  // Map values iterate in insertion order; reversing first makes ties on
  // createdAt (same-ms applications) resolve to most-recently-applied first.
  // The sort itself is stable, so same-ms ordering stays deterministic.
  return [...affiliates.values()]
    .reverse()
    .filter((account) => status === undefined || account.status === status)
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
}

export type AffiliateAdminAction = "approve" | "reject" | "suspend"

/**
 * Server-side status machine. Each action lists the statuses it may be
 * applied from; any other combination is an invalid transition and the
 * library functions throw `AffiliateTransitionError` (the API answers 409).
 * `rejected` is terminal — there is deliberately no un-reject action.
 *
 *   pending   → approve → active  |  reject → rejected
 *   active    → suspend → suspended
 *   suspended → approve → active (reactivate)  |  reject → rejected
 *
 * This mirrors `actionsFor` in `src/components/admin/affiliates-screen.tsx`,
 * which only renders buttons for legal transitions.
 */
const AFFILIATE_TRANSITIONS: Record<
  AffiliateAdminAction,
  { to: AffiliateStatus; from: readonly AffiliateStatus[] }
> = {
  approve: { to: "active", from: ["pending", "suspended"] },
  reject: { to: "rejected", from: ["pending", "suspended"] },
  suspend: { to: "suspended", from: ["active"] },
}

/** Thrown when an admin action is applied to a status that does not allow it. */
export class AffiliateTransitionError extends Error {
  constructor(
    public readonly action: AffiliateAdminAction,
    public readonly from: AffiliateStatus,
  ) {
    super(`Cannot ${action} an affiliate in status "${from}".`)
    this.name = "AffiliateTransitionError"
  }
}

function transition(id: string, action: AffiliateAdminAction): AffiliateAccount | null {
  const account = affiliates.get(id)
  if (!account) return null
  const rule = AFFILIATE_TRANSITIONS[action]
  if (!rule.from.includes(account.status)) {
    throw new AffiliateTransitionError(action, account.status)
  }
  account.status = rule.to
  return account
}

/** Approves a pending application or reactivates a suspended one. */
export function approveAffiliate(id: string): AffiliateAccount | null {
  return transition(id, "approve")
}

/** Rejects a pending or suspended application; rejected is terminal. */
export function rejectAffiliate(id: string): AffiliateAccount | null {
  return transition(id, "reject")
}

/** Suspends an active account; tracking stops recording for it. */
export function suspendAffiliate(id: string): AffiliateAccount | null {
  return transition(id, "suspend")
}

/**
 * Records a click on `code`'s tracking link. Only `active` affiliates accrue
 * clicks — pending/suspended/rejected codes return null so the endpoint can
 * answer 404 without leaking which codes exist. Bounded: when the click log
 * is full the oldest click is evicted.
 */
export function recordClick(
  code: string,
  meta: { userAgent?: string; ip?: string } = {},
): AffiliateClick | null {
  const account = getAffiliateByCode(code)
  if (!account || account.status !== "active") return null

  const click: AffiliateClick = {
    id: clickId(),
    code: account.code,
    affiliateId: account.id,
    at: nowIso(),
    ...(meta.userAgent ? { userAgent: meta.userAgent.slice(0, 300) } : {}),
    ...(meta.ip ? { ip: meta.ip } : {}),
  }
  if (clicks.length >= AFFILIATE_CLICKS_STORE_MAX) clicks.shift()
  clicks.push(click)
  return click
}

/**
 * Records a conversion against `code`. Same active-only rule as clicks.
 * `amountCents` is optional; when present the commission is computed from
 * the account's `commissionRatePct` and stored for reporting — there is no
 * payout pipeline.
 */
export function recordConversion(
  code: string,
  input: { amountCents?: number; at?: string } = {},
): AffiliateConversion | null {
  const account = getAffiliateByCode(code)
  if (!account || account.status !== "active") return null

  if (input.amountCents !== undefined) {
    if (!Number.isInteger(input.amountCents) || input.amountCents < 0) {
      throw new Error("amountCents must be a non-negative integer.")
    }
  }

  const conversion: AffiliateConversion = {
    id: conversionId(),
    code: account.code,
    affiliateId: account.id,
    at: input.at ?? nowIso(),
    ...(input.amountCents !== undefined
      ? {
          amountCents: input.amountCents,
          commissionCents: commissionCentsFor(account, input.amountCents),
        }
      : {}),
  }
  if (conversions.length >= AFFILIATE_CONVERSIONS_STORE_MAX) conversions.shift()
  conversions.push(conversion)
  return conversion
}

/**
 * Aggregated stats for one affiliate: total clicks, conversions, tracked
 * revenue, and computed commission. Conversions without an amount count
 * toward `conversions` but contribute nothing to the cent totals.
 */
export function statsForAffiliate(account: AffiliateAccount | string): AffiliateStats {
  const affiliateIdValue = typeof account === "string" ? account : account.id
  if (!affiliateIdValue) {
    return { clicks: 0, conversions: 0, revenueCents: 0, commissionCents: 0 }
  }

  let clickCount = 0
  let conversionCount = 0
  let revenueCents = 0
  let commissionCents = 0
  for (const click of clicks) {
    if (click.affiliateId === affiliateIdValue) clickCount += 1
  }
  for (const conversion of conversions) {
    if (conversion.affiliateId !== affiliateIdValue) continue
    conversionCount += 1
    revenueCents += conversion.amountCents ?? 0
    commissionCents += conversion.commissionCents ?? 0
  }
  return { clicks: clickCount, conversions: conversionCount, revenueCents, commissionCents }
}

/** Test hook: clears all affiliate accounts, clicks, and conversions. */
export function clearAffiliateStoreForTests(): void {
  affiliates.clear()
  affiliatesByUser.clear()
  affiliatesByEmail.clear()
  affiliatesByCode.clear()
  clicks.length = 0
  conversions.length = 0
}
