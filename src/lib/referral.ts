/**
 * Referral attribution capture.
 *
 * There is no referral backend yet (see the TODO in
 * `src/components/site/referral-share.tsx`), so attribution is a
 * best-effort client-side hand-off:
 *
 * 1. The `/r/[code]` landing page validates the path segment and calls
 *    `storeReferralCode`; `ReferralTracker` on `/referral` does the same for
 *    legacy `?ref=` links. Both persist the `SPN-XXXX-XXXX` code in
 *    localStorage.
 * 2. The auth dialog attaches the stored code to the mock session on
 *    sign-in / workspace creation via `consumeStoredReferralCode`, so the code
 *    survives the auth round-trip and is available to whatever backend lands
 *    next. Codes are consumed once to avoid double attribution.
 */

export const REFERRAL_PARAM = "ref"
export const REFERRAL_STORAGE_KEY = "spindle.referral-invite"

/** Key holding the visitor's own share code (written by `referral-share.tsx`). */
export const REFERRAL_OWN_CODE_KEY = "spindle.referral-code"

/** Matches the `SPN-XXXX-XXXX` codes generated by `referral-share.tsx`. */
export const REFERRAL_CODE_PATTERN = /^SPN-[A-Z2-9]{4}-[A-Z2-9]{4}$/

/**
 * Matches user-chosen vanity codes: `SPN-` followed by a 4–20 char slug that
 * starts and ends with an alphanumeric and may contain dashes in between
 * (e.g. `SPN-BOGDAN`, `SPN-LAB-GEAR`). Slugs that would collide with the
 * generated `SPN-XXXX-XXXX` shape are rejected by
 * `normalizeReferralVanityCode`.
 */
export const REFERRAL_VANITY_PATTERN = /^SPN-[A-Z0-9](?:[A-Z0-9-]{2,18}[A-Z0-9])$/

export const REFERRAL_VANITY_MIN_LENGTH = 4
export const REFERRAL_VANITY_MAX_LENGTH = 20

export function isReferralCode(value: string | null | undefined): value is string {
  return typeof value === "string" && REFERRAL_CODE_PATTERN.test(value)
}

export function isVanityReferralCode(value: string | null | undefined): value is string {
  return typeof value === "string" && REFERRAL_VANITY_PATTERN.test(value)
}

/** True for either generated (`SPN-XXXX-XXXX`) or vanity (`SPN-<slug>`) codes. */
export function isAnyReferralCode(value: string | null | undefined): value is string {
  return isReferralCode(value) || isVanityReferralCode(value)
}

/**
 * Normalizes a user-supplied vanity code into its canonical `SPN-<SLUG>`
 * form. Accepts the slug with or without the `SPN-` prefix, any case, and
 * surrounding whitespace. Returns null for anything that cannot become a
 * valid, non-colliding vanity code.
 */
export function normalizeReferralVanityCode(input: string): string | null {
  let slug = input.trim().toUpperCase()
  if (slug.startsWith("SPN-")) slug = slug.slice(4)
  if (
    slug.length < REFERRAL_VANITY_MIN_LENGTH ||
    slug.length > REFERRAL_VANITY_MAX_LENGTH ||
    !/^[A-Z0-9](?:[A-Z0-9-]*[A-Z0-9])?$/.test(slug)
  ) {
    return null
  }
  const candidate = `SPN-${slug}`
  // Reject slugs that reproduce the generated `SPN-XXXX-XXXX` shape so the
  // two namespaces never overlap.
  if (REFERRAL_CODE_PATTERN.test(candidate)) return null
  return candidate
}

/**
 * Builds the canonical share URL for a referral code: `/r/<code>` with UTM
 * parameters so downstream analytics can attribute signups to the share
 * channel. The landing page ignores the query string — the code lives in
 * the path.
 */
export function buildReferralShareUrl(siteUrl: string, code: string): string {
  const base = siteUrl.replace(/\/+$/, "")
  const params = new URLSearchParams({
    utm_source: "referral",
    utm_medium: "share",
    utm_campaign: "referral",
    utm_content: code,
  })
  return `${base}/r/${encodeURIComponent(code)}?${params.toString()}`
}

/** Extracts and validates the referral code from a URL or query string. */
export function referralCodeFromSearch(search: string): string | null {
  const params = new URLSearchParams(search.startsWith("?") ? search.slice(1) : search)
  const code = params.get(REFERRAL_PARAM)
  return isAnyReferralCode(code) ? code : null
}

/** Persists an inbound referral code. Ignores invalid or own-browser codes. */
export function storeReferralCode(code: string | null, ownCode?: string | null): void {
  if (typeof window === "undefined" || !isAnyReferralCode(code)) return
  // Self-referrals carry no attribution value.
  if (ownCode && code === ownCode) return
  try {
    window.localStorage.setItem(REFERRAL_STORAGE_KEY, code)
  } catch {
    // Storage unavailable (private mode) — attribution is best-effort.
  }
}

/**
 * Reads the visitor's own share code, used to drop self-referrals. Returns
 * null when storage is unavailable or nothing was generated yet.
 */
export function readOwnReferralCode(): string | null {
  if (typeof window === "undefined") return null
  try {
    const stored = window.localStorage.getItem(REFERRAL_OWN_CODE_KEY)
    return isAnyReferralCode(stored) ? stored : null
  } catch {
    return null
  }
}

export function readStoredReferralCode(): string | null {
  if (typeof window === "undefined") return null
  try {
    const stored = window.localStorage.getItem(REFERRAL_STORAGE_KEY)
    return isAnyReferralCode(stored) ? stored : null
  } catch {
    return null
  }
}

/**
 * Returns the pending referral code and clears it, so a code attributes at
 * most one auth completion.
 */
export function consumeStoredReferralCode(): string | null {
  const code = readStoredReferralCode()
  if (code && typeof window !== "undefined") {
    try {
      window.localStorage.removeItem(REFERRAL_STORAGE_KEY)
    } catch {
      // Ignore — a stale code simply attributes again on the next signup.
    }
  }
  return code
}
