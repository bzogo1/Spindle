#!/usr/bin/env node
// Turns the webpack bundle analyzer output (.next/analyze/client.html) into a
// per-route top-modules report. Run via `npm run analyze`, which performs the
// ANALYZE=true webpack build first.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const analyzeDir = join(root, ".next", "analyze")
const reportPath = join(root, "docs", "performance", "bundle-report.md")

// The three heaviest distinct client shapes: marketing home, MDX docs guide,
// and the collaboration page (globes, presence, chat).
const ROUTES = [
  { route: "/", entrypoint: "app/(site)/page" },
  { route: "/docs/[slug]", entrypoint: "app/(site)/docs/[slug]/page" },
  { route: "/collaboration", entrypoint: "app/(site)/collaboration/page" },
]

function loadChartData(file) {
  const html = readFileSync(file, "utf8")
  const match = html.match(/window\.chartData = (\[.*?\]);/s)
  if (!match) throw new Error(`No window.chartData found in ${file}`)
  return JSON.parse(match[1])
}

// Leaf modules carry parsedSize/gzipSize; folder and concatenated-module
// nodes only carry `groups` (ContentFolder carries sizes too, so recurse on
// `groups` first and never count a node that has children).
function collectModules(node, out = []) {
  if (Array.isArray(node.groups) && node.groups.length > 0) {
    for (const child of node.groups) collectModules(child, out)
    return out
  }
  if (typeof node.gzipSize === "number" || typeof node.parsedSize === "number") {
    out.push(node)
  }
  return out
}

function fmt(bytes) {
  if (bytes == null) return "—"
  if (bytes < 1024) return `${bytes} B`
  return `${(bytes / 1024).toFixed(1)} kB`
}

const chartData = loadChartData(join(analyzeDir, "client.html"))

// entrypoint name -> Set of module paths with their largest seen gzipSize
function modulesForEntrypoint(name) {
  const modules = new Map()
  for (const asset of chartData) {
    if (!asset.isInitialByEntrypoint?.[name]) continue
    for (const mod of collectModules(asset)) {
      const key = mod.path || mod.label
      const prev = modules.get(key)
      const gzip = mod.gzipSize ?? 0
      if (!prev || gzip > prev.gzipSize) {
        modules.set(key, { label: mod.label, gzipSize: mod.gzipSize ?? null })
      }
    }
  }
  return [...modules.values()].sort((a, b) => (b.gzipSize ?? 0) - (a.gzipSize ?? 0))
}

// ---- duplicate package detection across the whole client bundle ----
const PKG_RE = /node_modules\/((?:@[^/]+\/)?[^/]+)/g
const installs = new Map() // package -> Set of install prefixes
const present = new Set()

for (const asset of chartData) {
  for (const mod of collectModules(asset)) {
    const p = mod.path || mod.label || ""
    const matches = [...p.matchAll(PKG_RE)]
    if (matches.length === 0) continue
    const last = matches[matches.length - 1]
    present.add(last[1])
    const prefix = p.slice(0, p.indexOf(last[0]) + last[0].length)
    if (!installs.has(last[1])) installs.set(last[1], new Set())
    installs.get(last[1]).add(prefix)
  }
}

const duplicated = [...installs.entries()]
  .filter(([, prefixes]) => prefixes.size > 1)
  .map(([pkg, prefixes]) => ({ pkg, count: prefixes.size, prefixes: [...prefixes] }))
  .sort((a, b) => b.count - a.count)

// Known alias pairs worth calling out explicitly.
const ALIAS_PAIRS = [
  ["motion", "framer-motion"],
  ["@radix-ui/react-use-controllable-state", "radix-ui"],
]
const aliasFindings = ALIAS_PAIRS.filter(([a, b]) => present.has(a) && present.has(b))

// ---- report ----
const lines = []
lines.push("# Client bundle report")
lines.push("")
lines.push(
  `Generated by \`npm run analyze\` on ${new Date().toISOString().slice(0, 10)}. ` +
    "Source data: `.next/analyze/client.html` (webpack bundle analyzer, `ANALYZE=true next build --webpack`). " +
    "Module sizes are gzip estimates per module; routes list modules in their initial client chunks.",
)
lines.push("")
lines.push("Interactive reports: `.next/analyze/client.html`, `nodejs.html`, `edge.html`.")
lines.push("")

for (const { route, entrypoint } of ROUTES) {
  const modules = modulesForEntrypoint(entrypoint)
  const total = modules.reduce((sum, m) => sum + (m.gzipSize ?? 0), 0)
  lines.push(`## \`${route}\``)
  lines.push("")
  lines.push(`Initial client modules: ${modules.length} · total gzip ≈ ${fmt(total)}`)
  lines.push("")
  lines.push("| # | Module | Gzip |")
  lines.push("| - | ------ | ---- |")
  modules.slice(0, 10).forEach((m, i) => {
    lines.push(`| ${i + 1} | \`${m.label}\` | ${fmt(m.gzipSize)} |`)
  })
  lines.push("")
}

lines.push("## Duplicated packages")
lines.push("")
if (duplicated.length === 0 && aliasFindings.length === 0) {
  lines.push("No duplicated packages detected.")
} else {
  for (const d of duplicated) {
    lines.push(`- \`${d.pkg}\` resolved from ${d.count} locations:`)
    for (const prefix of d.prefixes.slice(0, 5)) lines.push(`  - \`${prefix}\``)
  }
  for (const [a, b] of aliasFindings) {
    lines.push(`- Both \`${a}\` and \`${b}\` are present in the client bundle.`)
  }
}
lines.push("")

mkdirSync(dirname(reportPath), { recursive: true })
writeFileSync(reportPath, lines.join("\n"))
console.log(`Bundle report written to ${reportPath}`)
for (const { route, entrypoint } of ROUTES) {
  console.log(`${route}: ${modulesForEntrypoint(entrypoint).length} initial modules`)
}
if (duplicated.length)
  console.log(`Duplicated packages: ${duplicated.map((d) => d.pkg).join(", ")}`)
